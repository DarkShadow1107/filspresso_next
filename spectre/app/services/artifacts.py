@dataclass(frozen=True)
class RenderedArtifact:
    data: bytes
    extension: str
    content_type: str


def _safe_spreadsheet_value(value: object) -> str:
    text = str(value)
    return f"'{text}" if text.startswith(("=", "+", "-", "@")) else text


def render_artifact(
    kind: ArtifactKind,
    title: str,
    content: str,
    sections: list[dict[str, object]],
) -> RenderedArtifact:
    if kind == ArtifactKind.MARKDOWN:
        body = f"# {title}\n\n{content}\n"
        for section in sections:
            body += f"\n## {section.get('title', 'Section')}\n\n{section.get('body', '')}\n"
        return RenderedArtifact(body.encode("utf-8"), "md", "text/markdown")

    if kind == ArtifactKind.DOCX:
        document = Document()
        document.add_heading(title, 0)
        if content:
            document.add_paragraph(content)
        for section in sections:
            document.add_heading(str(section.get("title", "Section")), level=1)
            document.add_paragraph(str(section.get("body", "")))
        buffer = io.BytesIO()
        document.save(buffer)
        return RenderedArtifact(
            buffer.getvalue(),
            "docx",
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        )

    if kind == ArtifactKind.XLSX:
        workbook = Workbook()
        sheet = workbook.active
        sheet.title = "Research"
        sheet.append(["Spectre Artifact", _safe_spreadsheet_value(title)])
        sheet.append(["Summary", _safe_spreadsheet_value(content)])
        for section in sections:
            sheet.append(
                [
                    _safe_spreadsheet_value(section.get("title", "Section")),
                    _safe_spreadsheet_value(section.get("body", "")),
                ]
            )
        sheet.column_dimensions["A"].width = 28
        sheet.column_dimensions["B"].width = 100
        buffer = io.BytesIO()
        workbook.save(buffer)
        return RenderedArtifact(
            buffer.getvalue(),
            "xlsx",
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        )

    if kind == ArtifactKind.PPTX:
        presentation = Presentation()
        title_slide = presentation.slides.add_slide(presentation.slide_layouts[0])
        title_slide.shapes.title.text = title
        title_slide.placeholders[1].text = "Generated by Spectre"
        if content:
            summary_slide = presentation.slides.add_slide(presentation.slide_layouts[1])
            summary_slide.shapes.title.text = "Executive Summary"
            summary_slide.placeholders[1].text = content
        for section in sections:
            slide = presentation.slides.add_slide(presentation.slide_layouts[1])
            slide.shapes.title.text = str(section.get("title", "Section"))
            slide.placeholders[1].text = str(section.get("body", ""))
        buffer = io.BytesIO()
        presentation.save(buffer)
        return RenderedArtifact(
            buffer.getvalue(),
            "pptx",
            "application/vnd.openxmlformats-officedocument.presentationml.presentation",
        )

    if kind == ArtifactKind.PDF:
        buffer = io.BytesIO()
        canvas = Canvas(buffer, pagesize=A4)
        _, height = A4
        cursor = height - 54

        def write_block(heading: str, text: str) -> None:
            nonlocal cursor
            canvas.setFont("Helvetica-Bold", 14)
            canvas.drawString(48, cursor, heading)
            cursor -= 22
            canvas.setFont("Helvetica", 10)
            for line in textwrap.wrap(text, width=96) or [""]:
                if cursor < 54:
                    canvas.showPage()
                    cursor = height - 54
                    canvas.setFont("Helvetica", 10)
                canvas.drawString(48, cursor, line)
                cursor -= 14
            cursor -= 12

        write_block(title, content)
        for section in sections:
            write_block(str(section.get("title", "Section")), str(section.get("body", "")))
        canvas.save()
        return RenderedArtifact(buffer.getvalue(), "pdf", "application/pdf")

    raise ValueError(f"Unsupported artifact kind: {kind}")


def _minio_endpoint_url() -> str:
    endpoint = get_settings().minio_endpoint.rstrip("/")
    if endpoint.startswith(("http://", "https://")):
        return endpoint
    return f"http://{endpoint}"


class MinioArtifactStore:
    """Private S3-compatible storage for generated artifacts."""

    def __init__(self, session: Any | None = None) -> None:
        settings = get_settings()
        self.bucket = settings.minio_bucket
        self._session = session or get_session()
        self._client_options = {
            "endpoint_url": _minio_endpoint_url(),
            "aws_access_key_id": settings.minio_access_key,
            "aws_secret_access_key": settings.minio_secret_key,
            "region_name": "us-east-1",
        }

    async def _ensure_bucket(self, client: object) -> None:
        try:
            await client.head_bucket(Bucket=self.bucket)  # type: ignore[attr-defined]
            return
        except ClientError as exc:
            if str(exc.response.get("Error", {}).get("Code")) not in {"404", "NoSuchBucket"}:
                raise

        try:
            await client.create_bucket(Bucket=self.bucket)  # type: ignore[attr-defined]
        except ClientError as exc:
            # Concurrent API and worker startup may create the same bucket.
            if str(exc.response.get("Error", {}).get("Code")) not in {
                "BucketAlreadyExists",
                "BucketAlreadyOwnedByYou",
            }:
                raise

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        async with self._session.create_client("s3", **self._client_options) as client:
            await self._ensure_bucket(client)
            await client.put_object(
                Bucket=self.bucket,
                Key=key,
                Body=data,
                ContentType=content_type,
            )

    async def get(self, key: str) -> bytes:
        async with self._session.create_client("s3", **self._client_options) as client:
            await self._ensure_bucket(client)
            response = await client.get_object(Bucket=self.bucket, Key=key)
            body = response["Body"]
            try:
                return await body.read()
            finally:
                body.close()


class LocalArtifactStore:
    """Read-only compatibility path for artifacts created before the MinIO rollout."""

    def __init__(self) -> None:
        self.root = Path("/srv/app/artifacts")
        if not self.root.exists():
            self.root = Path("artifacts")
        self.root.mkdir(parents=True, exist_ok=True)

    def put(self, key: str, data: bytes) -> None:
        path = self.root / key
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes:
        return (self.root / key).read_bytes()


async def create_artifact(
    db: AsyncSession,
    *,
    organization_id: UUID,
    created_by_id: UUID,
    kind: ArtifactKind,
    title: str,
    content: str,
    sections: list[dict[str, object]],
    case_id: UUID | None = None,
    revision: int = 1,
) -> Artifact:
    rendered = render_artifact(kind, title, content, sections)
    artifact_id = uuid.uuid4()
    storage_key = f"{organization_id}/{artifact_id}/r{revision}.{rendered.extension}"
    await MinioArtifactStore().put(storage_key, rendered.data, rendered.content_type)
    artifact = Artifact(
        id=artifact_id,
        organization_id=organization_id,
        case_id=case_id,
        created_by_id=created_by_id,
        kind=kind,
        title=title,
        storage_key=storage_key,
        revision=revision,
        metadata_json={
            "content_type": rendered.content_type,
            "byte_size": len(rendered.data),
            "rendering": "native",
            "storage_backend": "minio",
        },
    )
    db.add(artifact)
    return artifact


async def read_artifact_bytes(artifact: Artifact) -> bytes:
    if artifact.metadata_json.get("storage_backend") == "minio":
        return await MinioArtifactStore().get(artifact.storage_key)
    return LocalArtifactStore().get(artifact.storage_key)
