"""Browser E2E for the rebuilt Spectre workspace UI.

Run: python scripts/ui_e2e.py  (stack must be live on https://127.0.0.1:8080)
"""

import time

from playwright.sync_api import sync_playwright

BASE = "https://127.0.0.1:8080"
PASSWORD = "CorrectHorseBatteryStaple!42"


def main() -> None:
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page(ignore_https_errors=True)
        errors: list[str] = []
        page.on("pageerror", lambda exc: errors.append(str(exc)))

        email = f"ui-{int(time.time())}@example.com"

        page.goto(BASE, wait_until="networkidle")
        page.fill("form:has(h2:text('Create a local workspace')) input[name=display_name]", "UI Tester")
        page.fill("form:has(h2:text('Create a local workspace')) input[name=email]", email)
        page.fill("form:has(h2:text('Create a local workspace')) input[name=password]", PASSWORD)
        page.click("button:has-text('Create account')")
        page.wait_for_selector("text=LOCAL AGENT WORKSPACE", timeout=20000)
        print("registered + workspace visible")

        # A conversational request creates and immediately launches a workflow.
        page.fill("#goal", "Check that the live agent console streams events to the operator.")
        page.click(".profile-select button:has-text('fast')")
        page.click("button:has-text('Start workflow')")
        page.wait_for_selector("text=AGENT PLAN", timeout=15000)
        page.wait_for_selector(".event", timeout=90000)
        print("console streaming events")

        # Stop button appears while active; click it.
        stop = page.locator("button.danger:has-text('Stop run')").first
        stop.wait_for(state="visible", timeout=10000)
        stop.click()
        page.wait_for_timeout(3500)
        print("stop requested")

        # Documents panel upload (txt) + memory search.
        page.click("button[aria-label='Files']")
        payload = b"Spectre UI smoke memory paragraph with plenty of unique words."
        page.set_input_files("input[type=file]", {"name": "ui-note.txt", "mimeType": "text/plain", "buffer": payload})
        page.click("button:has-text('Ingest into memory')")
        page.wait_for_selector(".notice", timeout=60000)

        # Artifact creation via PDF (regression for the reset() crash).
        page.click("button[aria-label='Outputs']")
        page.select_option("select[name=kind]", "pdf")
        page.fill("input[name=title]", "UI smoke brief")
        page.fill(
            "textarea[name=content]",
            "Executive summary generated by the automated UI end-to-end check.",
        )
        page.click("button:has-text('Create versioned artifact')")
        page.wait_for_selector(".case-card:has-text('UI smoke brief') button:has-text('download')", timeout=20000)
        with page.expect_download(timeout=20000):
            page.click("button:has-text('download')")
        print("pdf artifact created + downloaded without error")

        # Account deletion modal flow.
        page.click(".account-trigger")
        page.click("button:has-text('Delete account…')")
        page.fill("div.modal input[placeholder='DELETE']", "DELETE")
        page.fill("div.modal input[type=password]", PASSWORD)
        page.click("button:has-text('Permanently delete everything')")
        try:
            page.wait_for_selector("text=LOCAL-FIRST AGENTIC RESEARCH", timeout=20000)
        except Exception:
            modal_error = page.locator("div.modal .error").first
            if modal_error.count():
                print("modal error:", modal_error.text_content())
            raise
        print("account deleted -> landing")

        fatal = [e for e in errors if "401" not in e and "403" not in e]
        assert not fatal, f"page errors: {fatal}"
        browser.close()
        print("UI E2E PASSED")


if __name__ == "__main__":
    main()
